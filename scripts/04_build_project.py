"""
Step 4 - Build the QGIS project (CS12_Roadway_Enrichment.qgz).

* Local results group     : layers from data/output/CS12_Roadway_Enrichment.gpkg (styled)
* REST feeds group        : the three DC GIS ArcGIS REST layers (live, arcgisfeatureserver)
* Geoprocessing history   : written into the GeoPackage as table `geoprocessing_history`
                            (loaded in the project) plus docs/geoprocessing_history.md
* Basemap                 : OpenStreetMap XYZ tiles
Paths are saved relative, so the zipped folder opens anywhere.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import qgis_env as Q  # noqa: E402

Q.start()
from osgeo import ogr  # noqa: E402
from qgis.core import (  # noqa: E402
    QgsCategorizedSymbolRenderer, QgsCoordinateReferenceSystem, QgsDataSourceUri, QgsLineSymbol,
    QgsMarkerSymbol, QgsProject, QgsRasterLayer, QgsRendererCategory, QgsVectorLayer,
)

ogr.UseExceptions()
ROOT = Q.ROOT
GPKG = Q.OUT_GPKG
PROJECT = os.path.join(ROOT, "CS12_Roadway_Enrichment.qgz")

REST = {
    "REST - Construction Permits (DDOT TOPS, MapServer/23)":
        "https://maps2.dcgis.dc.gov/dcgis/rest/services/DCGIS_APPS/DDOT_TOPS/MapServer/23",
    "REST - Cityworks Service Requests (MapServer/1)":
        "https://maps2.dcgis.dc.gov/dcgis/rest/services/DDOT/Cityworks/MapServer/1",
    "REST - Roadway SubBlock (MapServer/162)":
        "https://maps2.dcgis.dc.gov/dcgis/rest/services/DCGIS_DATA/Transportation_WebMercator/MapServer/162",
}

# --------------------------------------------------------------------------------------
# 1. Geoprocessing history -> GeoPackage table + markdown
# --------------------------------------------------------------------------------------
hist = json.load(open(Q.HISTORY_JSON, encoding="utf-8"))
dl_log = []
dl_path = os.path.join(ROOT, "data", "raw", "download_log.json")
if os.path.exists(dl_path):
    dl_log = [json.loads(x) for x in open(dl_path, encoding="utf-8") if x.strip()]

ds = ogr.Open(GPKG, update=1)
if ds.GetLayerByName("geoprocessing_history"):
    ds.DeleteLayer("geoprocessing_history")
lyr = ds.CreateLayer("geoprocessing_history", geom_type=ogr.wkbNone)
for name, t in [("seq", ogr.OFTInteger), ("step", ogr.OFTString), ("algorithm", ogr.OFTString),
                ("note", ogr.OFTString), ("started", ogr.OFTString), ("seconds", ogr.OFTReal),
                ("parameters", ogr.OFTString), ("results", ogr.OFTString),
                ("python_command", ogr.OFTString)]:
    lyr.CreateField(ogr.FieldDefn(name, t))
rows = [{"step": f"00 Download {d['layer']}", "algorithm": "ArcGIS REST query (scripts/01_download.py)",
         "note": f"{d['written']:,} features; server WHERE: {d['server_where']}",
         "started": d["downloaded_utc"], "seconds": 0,
         "parameters": {"url": d["url"], "where": d["server_where"], "outSR": 26985},
         "results": {"layer": d["layer"], "count": d["written"]},
         "python_command": "01_download.py"} for d in dl_log] + hist
for i, h in enumerate(rows, 1):
    f = ogr.Feature(lyr.GetLayerDefn())
    f["seq"] = i
    for k in ("step", "algorithm", "note", "started", "python_command"):
        f[k] = str(h.get(k, ""))
    f["seconds"] = float(h.get("seconds", 0))
    f["parameters"] = json.dumps(h.get("parameters"))
    f["results"] = json.dumps(h.get("results"))
    lyr.CreateFeature(f)
ds = None

with open(os.path.join(Q.DOCS, "geoprocessing_history.md"), "w", encoding="utf-8") as md:
    md.write("# Geoprocessing history\n\nEvery data download and QGIS Processing call, in the order it ran. "
             "Generated by `scripts/04_build_project.py` from `docs/geoprocessing_history.json`. The same "
             "rows are in the GeoPackage table `geoprocessing_history`.\n\n")
    md.write("| # | Step | Algorithm | Note | Seconds |\n|---|---|---|---|---|\n")
    for i, h in enumerate(rows, 1):
        md.write(f"| {i} | {h['step']} | `{h['algorithm']}` | {h.get('note', '')} | {h.get('seconds', '')} |\n")
    md.write("\n## Parameters for each step\n")
    for i, h in enumerate(rows, 1):
        md.write(f"\n### {i}. {h['step']}\n\n```python\n{h['python_command']}\n```\n")

# --------------------------------------------------------------------------------------
# 2. Project + layers
# --------------------------------------------------------------------------------------
proj = QgsProject.instance()
proj.clear()
proj.setCrs(QgsCoordinateReferenceSystem("EPSG:3857"))
proj.setTitle("CS12 - Roadway Subblock enrichment: permits + Cityworks SRs")
root = proj.layerTreeRoot()


def gpkg_layer(table, title):
    lyr = QgsVectorLayer(f"{GPKG}|layername={table}", title, "ogr")
    assert lyr.isValid(), table
    return lyr


def add(group, lyr, visible=True):
    proj.addMapLayer(lyr, False)
    node = group.addLayer(lyr)
    node.setItemVisibilityChecked(visible)
    return lyr


g_res = root.addGroup("Results - local GeoPackage (CS12_Roadway_Enrichment.gpkg)")
g_rest = root.addGroup("REST service feeds (DC GIS, live)")
g_tab = root.addGroup("Tables")
g_base = root.addGroup("Basemap")

# Subblocks with BOTH permits and SRs - thick red line on top
both = gpkg_layer("roadway_subblock_permits_and_sr", "Subblocks with permits AND service requests (BOTH_FLAG = 1)")
both.setRenderer(both.renderer().__class__(QgsLineSymbol.createSimple({"color": "#d7191c", "width": "1.6"})))

snapped = gpkg_layer("permits_filtered_snapped", "Permits - filtered, SNAPPED to roadway")
snapped.setRenderer(QgsCategorizedSymbolRenderer("SNAP_STAT", [
    QgsRendererCategory("SNAPPED - street/service lane/ramp",
                        QgsMarkerSymbol.createSimple({"name": "circle", "color": "#2c7bb6", "size": "1.8",
                                                      "outline_color": "#ffffff", "outline_width": "0.2"}),
                        "Snapped to street / service lane / ramp (counted)"),
    QgsRendererCategory("SNAPPED - alley/driveway/other (not counted)",
                        QgsMarkerSymbol.createSimple({"name": "circle", "color": "#999999", "size": "1.6"}),
                        "Snapped to alley / driveway / other (not counted)"),
]))
add(g_res, snapped)

sr = gpkg_layer("cityworks_sr_filtered", "Cityworks service requests - filtered (open / pending / inspection complete)")
sr.setRenderer(sr.renderer().__class__(QgsMarkerSymbol.createSimple(
    {"name": "triangle", "color": "#fdae61", "size": "2.6", "outline_color": "#7f3b08", "outline_width": "0.3"})))
add(g_res, sr)

orig = gpkg_layer("permits_filtered_original", "Permits - filtered, ORIGINAL location (before snap)")
orig.setRenderer(orig.renderer().__class__(QgsMarkerSymbol.createSimple(
    {"name": "cross", "color": "#7b3294", "size": "2"})))
add(g_res, orig, visible=False)

lines = gpkg_layer("permit_snap_lines", "QA - permit snap displacement lines")
lines.setRenderer(lines.renderer().__class__(QgsLineSymbol.createSimple({"color": "#7b3294", "width": "0.4"})))
add(g_res, lines, visible=False)
add(g_res, both)  # below the points so they stay visible on top of the highlighted blocks

enr = gpkg_layer("roadway_subblock_enriched", "Roadway Subblock - ENRICHED (streets, service lanes, ramps)")
cats = [("Permits + SRs", "#d7191c", "1.2"), ("Permits only", "#2c7bb6", "0.9"),
        ("SRs only", "#fdae61", "0.9"), ("Neither", "#bdbdbd", "0.3")]
enr.setRenderer(QgsCategorizedSymbolRenderer("FLAG_CAT", [
    QgsRendererCategory(v, QgsLineSymbol.createSimple({"color": c, "width": w}), v) for v, c, w in cats]))
add(g_res, enr)

for t, title in [("summary_permits_by_subblock", "Summary - permits by subblock"),
                 ("summary_sr_by_subblock", "Summary - service requests by subblock"),
                 ("geoprocessing_history", "Geoprocessing history")]:
    add(g_tab, gpkg_layer(t, title))

# Save each style as the layer's default style inside the GeoPackage too
for lyr in (both, snapped, sr, orig, lines, enr):
    lyr.saveStyleToDatabase("cs12_default", "CS12 default style", True, "")

# REST feeds
rest_report = []
for title, url in REST.items():
    uri = QgsDataSourceUri()
    uri.setParam("url", url)
    uri.setParam("crs", "EPSG:3857")
    lyr = QgsVectorLayer(uri.uri(False), title, "arcgisfeatureserver")
    rest_report.append(f"{title}: valid={lyr.isValid()} features={lyr.featureCount() if lyr.isValid() else 'n/a'}")
    add(g_rest, lyr, visible=False)
    if "Cityworks" in title:
        # 1.5 M points: only draw when zoomed in
        lyr.setScaleBasedVisibility(True)
        lyr.setMinimumScale(25000)
print("\n".join(rest_report))

osm = QgsRasterLayer("type=xyz&url=https://tile.openstreetmap.org/{z}/{x}/{y}.png&zmax=19&zmin=0",
                     "OpenStreetMap", "wms")
add(g_base, osm)

# Zoom to DC
proj.viewSettings().setDefaultViewExtent(
    __import__("qgis.core", fromlist=["QgsReferencedRectangle"]).QgsReferencedRectangle(
        enr.extent(), enr.crs()))

md = proj.metadata()
with open(os.path.join(Q.DOCS, "validation_summary.txt"), encoding="utf-8") as fh:
    md.setAbstract(fh.read())
proj.setMetadata(md)
proj.writeEntryBool("Paths", "/Absolute", False)
ok = proj.write(PROJECT)
print("Project written:", ok, PROJECT)
